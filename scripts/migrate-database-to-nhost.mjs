import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { Client } from "pg";

const tables = [
  { name: "profiles", orderBy: "id" },
  { name: "records", orderBy: "id" },
  { name: "contact_people", orderBy: "id" },
  { name: "import_batches", orderBy: "id" },
  { name: "legacy_table_snapshots", orderBy: "id" },
  { name: "record_contacts", orderBy: "record_id, position" },
  { name: "import_rows", orderBy: "id" },
  { name: "audit_logs", orderBy: "id" },
  { name: "legacy_table_records", orderBy: "snapshot_id, original_record_id" },
];

const jsonColumns = new Map([
  ["import_batches", new Set(["counts"])],
  ["import_rows", new Set(["data"])],
  ["audit_logs", new Set(["old_data", "new_data"])],
  ["legacy_table_records", new Set(["record_data", "contacts"])],
]);

const schemaSql = `
create extension if not exists pgcrypto;

create type public.app_role as enum ('admin', 'editor', 'viewer');
create type public.audit_action as enum ('insert', 'update', 'delete', 'restore', 'import');
create type public.import_status as enum ('staged', 'applying', 'applied', 'failed');
create type public.import_category as enum ('new', 'changed', 'same', 'invalid', 'deleted_conflict');

create table public.profiles (
  id uuid primary key,
  display_name text,
  role public.app_role not null default 'viewer',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.records (
  id uuid primary key default gen_random_uuid(),
  display_order integer not null constraint records_display_order_check check (display_order > 0),
  member_registry_no text not null constraint records_member_registry_no_check check (btrim(member_registry_no) <> ''),
  trade_registry_no text constraint records_trade_registry_not_blank check (trade_registry_no is null or btrim(trade_registry_no) <> ''),
  profession_group text not null constraint records_profession_group_check check (btrim(profession_group) <> ''),
  status text not null constraint records_status_check check (btrim(status) <> ''),
  title text not null constraint records_title_check check (btrim(title) <> ''),
  officials text,
  origin text,
  vote_status text,
  notes text,
  district text,
  street text,
  registered_address text not null,
  phone_numbers text not null,
  version integer not null default 1 constraint records_version_check check (version > 0),
  created_at timestamptz not null default now(),
  created_by uuid,
  updated_at timestamptz not null default now(),
  updated_by uuid,
  deleted_at timestamptz,
  deleted_by uuid,
  row_color text constraint records_row_color_valid check (row_color is null or row_color in ('yellow', 'green', 'red', 'blue')),
  gift boolean not null default false,
  itso_status text constraint records_itso_status_check check (itso_status is null or itso_status in ('İTSO''DA', 'ONAYLANDI', 'RAKİP ONAYLATTI')),
  registration_date text,
  tax_office_account text,
  authority_signature text,
  constraint records_display_order_unique unique (display_order) deferrable,
  constraint records_member_registry_no_key unique (member_registry_no),
  constraint records_trade_registry_unique unique (trade_registry_no) deferrable
);

create table public.contact_people (
  id uuid primary key default gen_random_uuid(),
  display_name text not null check (btrim(display_name) <> ''),
  normalized_name text not null unique check (btrim(normalized_name) <> ''),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  whatsapp_number text,
  outreach_sent_at timestamptz,
  outreach_sent_by uuid,
  outreach_urgent_at timestamptz,
  outreach_urgent_by uuid
);

create table public.import_batches (
  id uuid primary key default gen_random_uuid(),
  file_name text not null,
  status public.import_status not null default 'staged',
  counts jsonb not null default '{}'::jsonb,
  created_by uuid not null,
  created_at timestamptz not null default now(),
  applied_at timestamptz
);

create table public.import_rows (
  id bigint generated by default as identity primary key,
  batch_id uuid not null references public.import_batches(id) on delete cascade,
  row_number integer not null,
  data jsonb not null,
  category public.import_category not null,
  validation_errors text[] not null default '{}',
  record_id uuid references public.records(id) on delete set null,
  staged_version integer,
  unique (batch_id, row_number)
);

create table public.audit_logs (
  id bigint generated by default as identity primary key,
  record_id uuid not null,
  action public.audit_action not null,
  old_data jsonb,
  new_data jsonb,
  changed_fields text[] not null default '{}',
  actor_id uuid,
  version_from integer,
  version_to integer,
  import_batch_id uuid references public.import_batches(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.record_contacts (
  record_id uuid not null references public.records(id) on delete cascade,
  contact_person_id uuid not null references public.contact_people(id) on delete restrict,
  position smallint not null check (position > 0),
  primary key (record_id, position),
  unique (record_id, contact_person_id)
);

create table public.legacy_table_snapshots (
  id uuid primary key default gen_random_uuid(),
  label text not null,
  source_file_name text not null,
  record_count integer not null check (record_count >= 0),
  created_by uuid,
  created_at timestamptz not null default now()
);

create table public.legacy_table_records (
  snapshot_id uuid not null references public.legacy_table_snapshots(id) on delete cascade,
  original_record_id uuid not null,
  record_data jsonb not null,
  contacts jsonb not null default '[]'::jsonb,
  version integer not null default 1,
  deleted_at timestamptz,
  deleted_by uuid,
  primary key (snapshot_id, original_record_id)
);
`;

function parseEnv(text) {
  return Object.fromEntries(
    text
      .split(/\r?\n/)
      .filter((line) => line && !line.startsWith("#"))
      .map((line) => {
        const separator = line.indexOf("=");
        return [line.slice(0, separator), line.slice(separator + 1)];
      }),
  );
}

function quoteIdentifier(value) {
  return `"${value.replaceAll('"', '""')}"`;
}

function normalizedJson(value) {
  if (Array.isArray(value)) return value.map(normalizedJson);
  if (value && typeof value === "object") {
    if (value instanceof Date) return value.toISOString();
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, normalizedJson(value[key])]),
    );
  }
  return value;
}

function digest(rows) {
  return createHash("sha256")
    .update(JSON.stringify(normalizedJson(rows)))
    .digest("hex");
}

async function readTable(client, table) {
  const result = await client.query(
    `select * from public.${quoteIdentifier(table.name)} order by ${table.orderBy}`,
  );
  return result.rows;
}

async function insertRows(client, tableName, rows) {
  if (rows.length === 0) return;
  const columns = Object.keys(rows[0]);
  const chunkSize = 200;
  for (let offset = 0; offset < rows.length; offset += chunkSize) {
    const chunk = rows.slice(offset, offset + chunkSize);
    const values = [];
    const placeholders = chunk.map((row) => {
      const rowPlaceholders = columns.map((column) => {
        const value = row[column];
        values.push(
          value !== null && jsonColumns.get(tableName)?.has(column)
            ? JSON.stringify(value)
            : value,
        );
        return `$${values.length}`;
      });
      return `(${rowPlaceholders.join(", ")})`;
    });
    try {
      await client.query(
        `insert into public.${quoteIdentifier(tableName)} (${columns.map(quoteIdentifier).join(", ")}) values ${placeholders.join(", ")}`,
        values,
      );
    } catch (error) {
      throw new Error(
        `${tableName} tablosu, ${offset + 1}-${offset + chunk.length} satırları: ${error.message}`,
        { cause: error },
      );
    }
  }
}

async function main() {
  const env = parseEnv(await readFile(".env.migration.local", "utf8"));
  if (!env.SOURCE_DATABASE_URL || !env.TARGET_DATABASE_URL) {
    throw new Error("SOURCE_DATABASE_URL ve TARGET_DATABASE_URL tanımlı olmalıdır.");
  }

  const options = { ssl: { rejectUnauthorized: false }, connectionTimeoutMillis: 15_000 };
  const source = new Client({ ...options, connectionString: env.SOURCE_DATABASE_URL });
  const target = new Client({ ...options, connectionString: env.TARGET_DATABASE_URL });
  await source.connect();
  await target.connect();

  try {
    const existing = await target.query(
      `select table_name from information_schema.tables where table_schema = 'public' and table_name = any($1::text[])`,
      [tables.map((table) => table.name)],
    );
    if (existing.rowCount > 0) {
      throw new Error(`Hedefte uygulama tabloları zaten var: ${existing.rows.map((row) => row.table_name).join(", ")}`);
    }

    const snapshot = {};
    for (const table of tables) snapshot[table.name] = await readTable(source, table);

    const stamp = new Date().toISOString().replaceAll(":", "-").replaceAll(".", "-");
    const backupDirectory = path.join(".migration-backups", stamp);
    await mkdir(backupDirectory, { recursive: true });
    await writeFile(
      path.join(backupDirectory, "supabase-public-data.json"),
      JSON.stringify(snapshot, null, 2),
      "utf8",
    );

    await target.query("begin");
    try {
      await target.query(schemaSql);
      for (const table of tables) await insertRows(target, table.name, snapshot[table.name]);
      await target.query(`select setval(pg_get_serial_sequence('public.import_rows', 'id'), greatest((select coalesce(max(id), 1) from public.import_rows), 1), true)`);
      await target.query(`select setval(pg_get_serial_sequence('public.audit_logs', 'id'), greatest((select coalesce(max(id), 1) from public.audit_logs), 1), true)`);
      await target.query("commit");
    } catch (error) {
      await target.query("rollback");
      throw error;
    }

    let valid = true;
    for (const table of tables) {
      const targetRows = await readTable(target, table);
      const sourceHash = digest(snapshot[table.name]);
      const targetHash = digest(targetRows);
      const matches = snapshot[table.name].length === targetRows.length && sourceHash === targetHash;
      valid &&= matches;
      console.log(`${table.name}: ${targetRows.length} satır - ${matches ? "DOĞRULANDI" : "UYUŞMAZLIK"}`);
    }
    if (!valid) throw new Error("Aktarım sonrası içerik doğrulaması başarısız oldu.");
    console.log(`Yerel yedek: ${backupDirectory}`);
    console.log("AKTARIM_BASARILI");
  } finally {
    await source.end();
    await target.end();
  }
}

main().catch((error) => {
  console.error(`AKTARIM_HATASI: ${error.message}`);
  process.exitCode = 1;
});
